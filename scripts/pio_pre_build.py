"""PlatformIO pre-build hook: generates build/cyd32_build_gen.h.

Inputs (environment variables, all optional):
  CYD32_VERSION       version string (default: git describe)
  CYD32_COMMIT        commit hash   (default: git rev-parse)
  CYD32_SOURCE_URL    public source URL shown on About/OTA portal
  CYD32_OTA_PUBKEY    path to PEM P-256 public key, slot 0 (default keys/ota_pub_0.pem)
  CYD32_OTA_PUBKEY2   path to PEM P-256 public key, slot 1 (default keys/ota_pub_1.pem)
  CYD32_OFFICIAL      "1" only for the upstream official release build
Only PUBLIC keys are ever read here.
"""
import os, subprocess, hashlib, base64
Import("env")  # noqa: F821

root = env.subst("$PROJECT_DIR")

def git(*a):
    try:
        return subprocess.check_output(["git", *a], cwd=root, stderr=subprocess.DEVNULL).decode().strip()
    except Exception:
        return ""

def load_pub(path):
    """Return 65-byte uncompressed P-256 point from a PEM SubjectPublicKeyInfo, or None."""
    if not path:
        return None
    p = path if os.path.isabs(path) else os.path.join(root, path)
    if not os.path.isfile(p):
        return None
    txt = open(p).read()
    if "PRIVATE" in txt:
        raise SystemExit("CYD32: refusing to read a PRIVATE key at build time: " + path)
    b64 = "".join(l for l in txt.splitlines() if l and not l.startswith("-----"))
    der = base64.b64decode(b64)
    # P-256 SPKI DER is 91 bytes; the point is the last 65 bytes (04||X||Y)
    if len(der) != 91 or der[-65] != 0x04:
        raise SystemExit("CYD32: not a P-256 public key: " + path)
    return der[-65:]

ver = os.environ.get("CYD32_VERSION") or git("describe", "--tags", "--always", "--dirty") or "0.0.0-dev"
commit = os.environ.get("CYD32_COMMIT") or git("rev-parse", "--short=12", "HEAD") or "unknown"
url = os.environ.get("CYD32_SOURCE_URL") or "https://github.com/b-air/CYD32"
official = os.environ.get("CYD32_OFFICIAL", "0") == "1"
keys = [load_pub(os.environ.get("CYD32_OTA_PUBKEY", "keys/ota_pub_0.pem")),
        load_pub(os.environ.get("CYD32_OTA_PUBKEY2", "keys/ota_pub_1.pem"))]

def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

out = ["/* Generated by scripts/pio_pre_build.py - do not edit */", "#pragma once", "#include <stdint.h>",
       f"#define CYD32_VERSION {c_str(ver)}", f"#define CYD32_COMMIT {c_str(commit)}",
       f"#define CYD32_SOURCE_URL {c_str(url)}", f"#define CYD32_OFFICIAL {1 if official else 0}",
       "#define CYD32_LICENSE \"AGPL-3.0-only\""]
for i, k in enumerate(keys):
    present = k is not None
    data = k if present else bytes(65)
    fp = hashlib.sha256(data).hexdigest()[:16] if present else "----------------"
    out.append(f"#define CYD32_KEY{i}_PRESENT {1 if present else 0}")
    out.append(f"#define CYD32_KEY{i}_FPR {c_str(fp)}")
    out.append(f"static const uint8_t cyd32_key{i}[65] = {{" + ",".join(f"0x{b:02x}" for b in data) + "};")
gen_dir = os.path.join(env.subst("$BUILD_DIR"), "gen")
os.makedirs(gen_dir, exist_ok=True)
with open(os.path.join(gen_dir, "cyd32_build_gen.h"), "w") as f:
    f.write("\n".join(out) + "\n")
env.Append(CPPPATH=[gen_dir])
print(f"CYD32 build: version={ver} commit={commit} official={official} keys={[k is not None for k in keys]}")
